/* supabase/scripts/build-seed.js — test content → supabase/seed.sql
   Reads apps/storefront/content/products/*.json (the storefront contract) and writes idempotent inserts.
   Ids are derived from the slug (md5 → uuid), so re-running updates the same rows.
   Run: node supabase/scripts/build-seed.js */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const SRC = path.join(ROOT, 'apps/storefront/content/products');
const OUT = path.join(ROOT, 'supabase/seed.sql');

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a || []).map(q).join(', ')}]::text[]`;
const json = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const id = (kind, slug) => `md5(${q(kind + ':' + slug)})::uuid`;

const lines = ['-- generated by supabase/scripts/build-seed.js — do not edit by hand', 'begin;'];
for (const file of fs.readdirSync(SRC).filter((f) => f.endsWith('.json')).sort()) {
  const { listing: l, release: r, copy: c, samples } = JSON.parse(fs.readFileSync(path.join(SRC, file), 'utf8'));
  const rid = id('release', l.slug);
  lines.push(`
-- ${l.slug}
insert into public.releases (id, discogs_release_id, discogs_master_id, label, cat_no, year, country, format, genre, style, tracklist)
values (${rid}, ${r.discogs_release_id ?? 'null'}, ${r.discogs_master_id ?? 'null'}, ${q(r.label)}, ${q(r.cat_no)}, ${r.year ?? 'null'}, ${q(r.country)}, ${q(r.format)}, ${arr(r.genre)}, ${arr(r.style)}, ${json(r.tracklist || [])})
on conflict (id) do update set label = excluded.label, cat_no = excluded.cat_no, year = excluded.year, country = excluded.country, format = excluded.format, genre = excluded.genre, style = excluded.style, tracklist = excluded.tracklist;
insert into public.release_lines (id, release_id, position, artist, title)
values (${id('line', l.slug + ':1')}, ${rid}, 1, ${q(r.artist)}, ${q(r.title)})
on conflict (id) do update set artist = excluded.artist, title = excluded.title;
insert into public.listings (id, slug, release_id, section, status, price_cents, currency, condition_media, condition_sleeve, sleeve_type, notes, photo_keys, import_source, published_at)
values (${id('listing', l.slug)}, ${q(l.slug)}, ${rid}, ${q(l.section)}, ${q(l.status)}, ${l.price ? l.price.amount : 'null'}, ${q(l.price ? l.price.currency : 'EUR')}, ${q(c.condition_media)}, ${q(c.condition_sleeve)}, 'original', ${q(c.notes)}, ${arr([r.cover].concat((c.photos || []).filter((p) => p !== r.cover)).filter(Boolean))}, ${json(Object.assign({ legacy_id: l.id }, l.source || {}))}, ${l.status === 'draft' ? 'null' : 'now()'})
on conflict (id) do update set section = excluded.section, status = excluded.status, price_cents = excluded.price_cents, currency = excluded.currency, condition_media = excluded.condition_media, condition_sleeve = excluded.condition_sleeve, sleeve_type = excluded.sleeve_type, notes = excluded.notes, photo_keys = excluded.photo_keys, import_source = excluded.import_source;`);
  (samples || []).forEach((s, i) => lines.push(
`insert into public.samples (id, release_id, track_position, title, audio_key, duration_s, source, sort)
values (${id('sample', l.slug + ':' + s.track_position)}, ${rid}, ${q(s.track_position)}, ${q(s.title)}, ${q(s.audio_url)}, ${s.duration ?? 'null'}, ${q(s.source)}, ${i})
on conflict (id) do update set title = excluded.title, audio_key = excluded.audio_key, duration_s = excluded.duration_s, source = excluded.source, sort = excluded.sort;`));
}
lines.push('commit;', '');
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${path.relative(ROOT, OUT)}`);
